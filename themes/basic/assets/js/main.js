(function() {
  var root = document.documentElement;
  var toggle = document.getElementById('theme-toggle');
  if (!toggle) return;

  toggle.addEventListener('click', function() {
    var next = root.getAttribute('data-theme') === 'dark' ? 'light' : 'dark';
    root.setAttribute('data-theme', next);
    localStorage.setItem('theme', next);
  });
})();


// Chart tooltips: bars carry data-tip; shown on hover and keyboard focus
(function() {
  document.querySelectorAll('.chart').forEach(function(fig) {
    var tip = document.createElement('div');
    tip.className = 'chart-tooltip';
    tip.hidden = true;
    fig.appendChild(tip);
    function show(bar) {
      var fr = fig.getBoundingClientRect();
      var mark = bar.querySelector('.chart-mark') || bar;
      var br = mark.getBoundingClientRect();
      tip.textContent = bar.getAttribute('data-tip');
      tip.style.left = (br.left + br.width / 2 - fr.left) + 'px';
      tip.style.top = (br.top - fr.top) + 'px';
      tip.hidden = false;
    }
    fig.querySelectorAll('.chart-bar').forEach(function(bar) {
      var title = bar.querySelector('title');
      if (title) title.remove();  // avoid the native tooltip doubling ours
      bar.addEventListener('pointerenter', function() { show(bar); });
      bar.addEventListener('focus', function() { show(bar); });
      bar.addEventListener('pointerleave', function() { tip.hidden = true; });
      bar.addEventListener('blur', function() { tip.hidden = true; });
    });
  });
})();

// Project filter buttons
(function() {
  var buttons = document.querySelectorAll('.filter[data-filter]');
  if (!buttons.length) return;
  var cards = document.querySelectorAll('.project-card[data-category], .race-tile[data-category]');
  buttons.forEach(function(btn) {
    btn.addEventListener('click', function() {
      var f = btn.getAttribute('data-filter');
      buttons.forEach(function(b) {
        var on = b === btn;
        b.classList.toggle('active', on);
        b.setAttribute('aria-pressed', on ? 'true' : 'false');
      });
      cards.forEach(function(c) { c.hidden = f !== 'all' && c.getAttribute('data-category') !== f; });
    });
  });
})();

// Tiles and cards: a soft light follows the pointer
(function() {
  document.querySelectorAll('.tile, .project-card, .post-summary, .run-tile, .shot').forEach(function(el) {
    el.addEventListener('pointermove', function(e) {
      var r = el.getBoundingClientRect();
      el.style.setProperty('--mx', (e.clientX - r.left) + 'px');
      el.style.setProperty('--my', (e.clientY - r.top) + 'px');
    });
  });
})();

// Content blocks fade in as they scroll into view (charts grow their bars)
(function() {
  if (!('IntersectionObserver' in window) || matchMedia('(prefers-reduced-motion: reduce)').matches) return;
  var els = document.querySelectorAll('main .chart, main .project-card, main .post-summary, main .race-group, main .shot-strip, main .cards .card, main .gear-list, main .talk-list > li, main .pub-list > li, main .gallery figure, main .section-posts');
  var io = new IntersectionObserver(function(entries) {
    entries.forEach(function(en) {
      if (en.isIntersecting) { en.target.classList.add('in'); io.unobserve(en.target); }
    });
  }, { rootMargin: '0px 0px -8% 0px' });
  els.forEach(function(el, i) {
    var r = el.getBoundingClientRect();
    if (r.top < innerHeight * 0.92) return;          // already on screen: no animation, no flash
    el.classList.add('reveal');
    io.observe(el);
  });
})();
